using System.Text.Json;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.ChangeTracking;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using OEESentinel.Domain.Entities;
using OEESentinel.Domain.ValueObjects;

namespace OEESentinel.Infrastructure.Persistence.Configurations;

public sealed class ProductionShiftConfiguration : IEntityTypeConfiguration<ProductionShift>
{
    private static readonly JsonSerializerOptions JsonOptions = new() { WriteIndented = false };

    private static bool BreakdownsEqual(DowntimeBreakdown a, DowntimeBreakdown b)
    {
        if (a.Entries.Count != b.Entries.Count) return false;
        foreach (var (key, val) in a.Entries)
        {
            if (!b.Entries.TryGetValue(key, out var other)) return false;
            if (Math.Abs(other.Seconds - val.Seconds) > 1e-6) return false;
        }
        return true;
    }

    private static readonly ValueComparer<DowntimeBreakdown> BreakdownComparer = new(
        (a, b) => BreakdownsEqual(a!, b!),
        v => v.Entries.Aggregate(0, (h, kv) =>
            HashCode.Combine(h, kv.Key.GetHashCode(), kv.Value.GetHashCode())),
        v => v); // DowntimeBreakdown is immutable; no snapshot needed.

    public void Configure(EntityTypeBuilder<ProductionShift> b)
    {
        b.ToTable("production_shifts", t =>
        {
            t.HasCheckConstraint("chk_shifts_window", "window_start < window_end");
            t.HasCheckConstraint("chk_shifts_totals",
                "total_parts >= 0 AND approved_parts >= 0 AND approved_parts <= total_parts");
            t.HasCheckConstraint("chk_shifts_availability", "availability BETWEEN 0 AND 1");
            t.HasCheckConstraint("chk_shifts_performance", "performance BETWEEN 0 AND 1");
            t.HasCheckConstraint("chk_shifts_quality", "quality BETWEEN 0 AND 1");
            t.HasCheckConstraint("chk_shifts_oee", "oee BETWEEN 0 AND 1");
            t.HasCheckConstraint("chk_shifts_no_self_supersede",
                "superseded_by_id IS NULL OR superseded_by_id <> id");
        });

        b.HasKey(s => s.Id);
        b.Property(s => s.Id).HasColumnName("id");

        b.Property(s => s.MachineCode)
            .HasColumnName("machine_code")
            .HasMaxLength(32)
            .HasConversion(v => v.Value, v => new MachineCode(v))
            .IsRequired();

        b.OwnsOne(s => s.Window, w =>
        {
            w.Property(x => x.Start).HasColumnName("window_start").IsRequired();
            w.Property(x => x.End).HasColumnName("window_end").IsRequired();
        });

        b.OwnsOne(s => s.Totals, t =>
        {
            t.Property(x => x.TotalParts).HasColumnName("total_parts").IsRequired();
            t.Property(x => x.ApprovedParts).HasColumnName("approved_parts").IsRequired();
            t.Ignore(x => x.RejectedParts); // generated by DB
        });

        b.OwnsOne(s => s.Metrics, m =>
        {
            m.Property(x => x.Availability)
                .HasColumnName("availability").HasColumnType("numeric(5,4)")
                .HasConversion(p => p.Value, v => new Percentage(v))
                .IsRequired();

            m.Property(x => x.Performance)
                .HasColumnName("performance").HasColumnType("numeric(5,4)")
                .HasConversion(p => p.Value, v => new Percentage(v))
                .IsRequired();

            m.Property(x => x.Quality)
                .HasColumnName("quality").HasColumnType("numeric(5,4)")
                .HasConversion(p => p.Value, v => new Percentage(v))
                .IsRequired();

            m.Property(x => x.OverallOee)
                .HasColumnName("oee").HasColumnType("numeric(5,4)")
                .HasConversion(p => p.Value, v => new Percentage(v))
                .IsRequired();
        });

        b.Property(s => s.Downtime)
            .HasColumnName("downtime_breakdown")
            .HasColumnType("jsonb")
            .HasConversion(
                v => JsonSerializer.Serialize(
                    v.Entries.ToDictionary(kvp => kvp.Key.Value, kvp => kvp.Value.Seconds),
                    JsonOptions),
                v => new DowntimeBreakdown(
                    (JsonSerializer.Deserialize<Dictionary<string, double>>(v, JsonOptions)
                        ?? new Dictionary<string, double>())
                        .ToDictionary(
                            kvp => new DowntimeReasonCode(kvp.Key),
                            kvp => new Duration(kvp.Value))),
                BreakdownComparer)
            .IsRequired();

        b.Property(s => s.SourceIngestionId).HasColumnName("source_ingestion_id").IsRequired();
        b.Property(s => s.SupersededBy).HasColumnName("superseded_by_id");
        b.Property(s => s.RecordedAt).HasColumnName("recorded_at")
            .HasDefaultValueSql("CURRENT_TIMESTAMP").IsRequired();

        b.HasOne<Machine>()
            .WithMany()
            .HasForeignKey(s => s.MachineCode)
            .HasPrincipalKey(m => m.Code)
            .HasConstraintName("fk_shifts_machine")
            .OnDelete(DeleteBehavior.Restrict);

        b.HasOne<LogIngestion>()
            .WithMany()
            .HasForeignKey(s => s.SourceIngestionId)
            .HasConstraintName("fk_shifts_ingestion")
            .OnDelete(DeleteBehavior.Restrict);

        b.HasOne<ProductionShift>()
            .WithMany()
            .HasForeignKey(s => s.SupersededBy)
            .HasConstraintName("fk_shifts_superseded_by")
            .OnDelete(DeleteBehavior.Restrict);

        b.HasIndex(s => s.SourceIngestionId)
            .HasDatabaseName("idx_production_shifts_ingestion");
    }
}